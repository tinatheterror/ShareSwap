// What happens to every column holding (or possibly holding) personal data when an account is deleted.
//
//   keep       the value stays as it is: it is not personal, or it belongs to a record the other party or the
//              books still need (see `retention`).
//   anonymize  the row stays and the value is replaced by a neutral placeholder or scrubbed of free text.
//   delete     the value is emptied, or, for a table whose `rows` is "delete", the user's rows are removed.
//
// Every column of every table is listed exactly once, so the manifest test fails when a column is added to
// the schema without a decision here. `userColumns` lists the columns that point at a user (foreign keys,
// plus the plain integer ids the schema does not declare as foreign keys); the anonymizer re-points or
// follows them. The tables the app creates for itself at runtime are in RUNTIME_TABLE_MANIFEST.
//
// Treatments apply to the rows and the side of a shared record that belong to the deleting user: the
// counterparty's own columns on a shared booking stay.

import type { RetentionWindow } from "./retention";

export type Treatment = "keep" | "anonymize" | "delete";

export type TableManifest = {
  /** "delete": the user's rows are removed. "retain": the rows stay, and the column treatments apply. */
  rows: "retain" | "delete";
  /** The window a kept record stays for, named in retention.ts; null when nothing is kept for a purpose. */
  retention: RetentionWindow | null;
  note: string;
  userColumns: string[];
  /** userColumns that, when they hold the deleting user, remove the whole row instead of scrubbing it. */
  deleteRowsWhere?: string[];
  /**
   * Columns of `delete` that are kept instead when the booking is evidence: it has a security claim, or a handoff
   * or return dispute was raised on it. They stay under the table's retention window.
   */
  evidence?: string[];
  keep: string[];
  anonymize: string[];
  delete: string[];
};

